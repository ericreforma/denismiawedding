/**
 * Turns the couple's full-resolution gallery into something a web page can
 * actually serve, and writes the manifest the strip lays itself out from.
 *
 *   node scripts/build-gallery.mjs
 *
 * Input   public/gallery/            ~0.96GB of camera JPEGs, git-ignored
 * Output  public/gallery-web/thumb/  520px tall, for the scrolling strip
 *         public/gallery-web/full/   1280px long edge, for the lightbox
 *         src/data/gallery.ts        filename + intrinsic size of each
 *
 * The manifest carries each image's dimensions so the strip can reserve the
 * right width before anything loads — without it the row jumps about as
 * images arrive, and lazy loading becomes useless because the browser cannot
 * tell what is off screen.
 */
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const SRC = "public/gallery";
const OUT = "public/gallery-web";
const MANIFEST = "src/data/gallery.ts";

/** Already used elsewhere on the page, so they are not repeated here. */
const EXCLUDE = new Set(["a-8", "a-36", "a-53", "a-72", "a-116"]);

const THUMB_HEIGHT = 520; // 2x a 260px row
const FULL_LONG_EDGE = 1280;

/** `a-10` sorts after `a-9`, which a plain string sort gets wrong. */
const naturalOrder = (a, b) =>
  a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });

const stem = (f) => path.basename(f).replace(/\.[^.]+$/, "");

fs.mkdirSync(path.join(OUT, "thumb"), { recursive: true });
fs.mkdirSync(path.join(OUT, "full"), { recursive: true });

const files = fs
  .readdirSync(SRC)
  // `._x.jpg` are macOS AppleDouble sidecars that come along when copying
  // off a Mac. They are 4KB of metadata, not images, and sharp throws on them.
  .filter((f) => !f.startsWith("._"))
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  .filter((f) => !EXCLUDE.has(stem(f)))
  .sort(naturalOrder);

console.log(`${files.length} images to process`);

const entries = [];
let bytesIn = 0;
let bytesOut = 0;

for (const [i, file] of files.entries()) {
  const name = stem(file);
  const src = path.join(SRC, file);
  const thumb = path.join(OUT, "thumb", `${name}.webp`);
  const full = path.join(OUT, "full", `${name}.webp`);

  bytesIn += fs.statSync(src).size;

  // `rotate()` with no argument applies the EXIF orientation and clears it,
  // so a phone-shot portrait does not come out on its side.
  await sharp(src)
    .rotate()
    .resize({ height: THUMB_HEIGHT, withoutEnlargement: true })
    .webp({ quality: 76, effort: 5 })
    .toFile(thumb);

  await sharp(src)
    .rotate()
    .resize({
      width: FULL_LONG_EDGE,
      height: FULL_LONG_EDGE,
      fit: "inside",
      withoutEnlargement: true,
    })
    .webp({ quality: 80, effort: 5 })
    .toFile(full);

  const m = await sharp(thumb).metadata();
  bytesOut += fs.statSync(thumb).size + fs.statSync(full).size;
  entries.push({ name, w: m.width, h: m.height });

  if ((i + 1) % 20 === 0 || i === files.length - 1) {
    console.log(`  ${i + 1}/${files.length}`);
  }
}

const body = `/**
 * Generated by scripts/build-gallery.mjs — do not edit by hand.
 *
 * \`w\`/\`h\` are the thumbnail's pixel size. The strip only needs the ratio,
 * but keeping both means a row can reserve its exact width before any image
 * has loaded.
 */
const BASE = process.env.NEXT_PUBLIC_BASE_PATH ?? "";

export type GalleryPhoto = {
  /** Scaled to the row height, shown in the strip. */
  thumb: string;
  /** Larger copy, fetched only when the lightbox opens. */
  full: string;
  w: number;
  h: number;
};

export const GALLERY: GalleryPhoto[] = [
${entries
  .map(
    (e) =>
      `  { thumb: \`\${BASE}/gallery-web/thumb/${e.name}.webp\`, full: \`\${BASE}/gallery-web/full/${e.name}.webp\`, w: ${e.w}, h: ${e.h} },`,
  )
  .join("\n")}
];
`;

fs.writeFileSync(MANIFEST, body);

const mb = (n) => (n / 1048576).toFixed(1);
console.log(`\nwrote ${entries.length} entries to ${MANIFEST}`);
console.log(`${mb(bytesIn)}MB in -> ${mb(bytesOut)}MB out`);
